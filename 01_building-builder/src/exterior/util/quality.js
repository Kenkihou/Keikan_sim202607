/* ============================================================
   作図中の「粗さ」を切り替えるための小さな共有スイッチ

   芝の葉・砂利の粒・樹木の葉は数万個のインスタンスで作っているため、
   スライダーやギズモを動かすたびに全部作り直すと 1回 60ms 前後かかり、
   毎秒60回のイベントに追いつけず、手の動きから大きく遅れてしまう。

   そこで【ドラッグ中は数を間引いた粗い形】で即座に見せ、
   【手を離したら本来の細かさ】で作り直す。数を数える側は thin() を通すだけでよい。
   ============================================================ */

let detail = 1;                       // 1 = 本来の細かさ

export function setDetail(v){ detail = v; }
export const getDetail = () => detail;
export const isDraft = () => detail < 1;

/* 「多いほど重い」数量（インスタンス数など）を今の粗さに合わせて間引く */
export function thin(n){
  if (detail >= 1) return n;
  return Math.max(1, Math.round(n * detail));
}
